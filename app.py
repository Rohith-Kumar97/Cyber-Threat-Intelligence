@app.route("/analyze", methods=["POST"])
@login_required
def analyze():

    email = request.form.get(
        "email", ""
    ).strip().lower()

    scoring_rules = {
        "urgent": 10,
        "suspended": 20,
        "verify your account": 15,
        "update your password": 20,
        "click this link": 15,
        "password": 10,
        "bank details": 25
    }

    found = []
    score = 0

    if not email:

        result = "Please enter email content."
        status = "No Input"
        level = "Not Analyzed"

    else:

        for word, points in scoring_rules.items():

            if word == "password" and "update your password" in email:
                continue

            if word in email:
                found.append(word)
                score += points

        score = min(score, 100)

        if score >= 60:
            level = "High Risk"
            status = "Potential Phishing"

        elif score >= 30:
            level = "Medium Risk"
            status = "Suspicious Email"

        else:
            level = "Low Risk"
            status = "No obvious phishing indicators"

        if found:
            result = (
                "Warning! Suspicious indicators detected: "
                + ", ".join(found)
            )
        else:
            result = (
                "No obvious suspicious keywords detected. "
                "This does not guarantee the email is safe."
            )

    report = {
        "scan_type": "Email Threat Analysis",
        "input_text": email[:2000],
        "status": status,
        "risk_score": score,
        "risk_level": level,
        "indicators": found
    }

    if email:
        session["latest_report"] = report
        save_scan(report)

    return render_template(
        "index.html",
        result=result,
        status=status,
        risk_score=score,
        risk_level=level,
        found=found
    )


