@app.route("/scan_url", methods=["POST"])
@login_required
def scan_url():

    url = request.form.get("url", "").strip()

    if not url:

        return render_template(
            "index.html",
            url_result="Please enter a URL.",
            url_status="No Input",
            url_score=0,
            url_level="Not Analyzed",
            url_found=[]
        )

    if not re.match(r"^https?://", url, re.I):
        url = "http://" + url

    try:

        parsed = urlparse(url)
        domain = parsed.hostname or ""

        # Validate port syntax
        port = parsed.port

    except ValueError:

        return render_template(
            "index.html",
            url_result="Invalid URL.",
            url_status="Invalid URL",
            url_score=0,
            url_level="Not Analyzed",
            url_found=[]
        )

    domain = domain.lower().rstrip(".")

    if (
        not domain
        or "." not in domain
        or any(ch.isspace() for ch in domain)
    ):

        return render_template(
            "index.html",
            url_result="Invalid URL.",
            url_status="Invalid URL",
            url_score=0,
            url_level="Not Analyzed",
            url_found=[]
        )

    score = 0
    found = []

    def add_risk(points, message):

        nonlocal score
        score += points
        found.append(message)

    if parsed.scheme.lower() == "http":
        add_risk(15, "Website does not use HTTPS")

    try:

        ipaddress.ip_address(domain)

        add_risk(
            25,
            "Website uses an IP address instead of a domain"
        )

    except ValueError:
        pass

    if "@" in parsed.netloc:
        add_risk(25, "URL contains an @ symbol")

    shorteners = {
        "bit.ly", "tinyurl.com", "t.co", "is.gd",
        "cutt.ly", "shorturl.at", "rb.gy", "ow.ly"
    }

    if domain in shorteners:
        add_risk(20, "URL uses a known link-shortening service")

    if "xn--" in domain:
        add_risk(25, "Domain contains Punycode characters")

    risky_extensions = {
        ".zip", ".click", ".top", ".xyz",
        ".work", ".gq", ".tk", ".ml", ".cf"
    }

    if any(domain.endswith(ext) for ext in risky_extensions):
        add_risk(15, "Domain uses a potentially risky extension")

    if len(domain.split(".")) > 4:
        add_risk(15, "URL contains too many subdomains")

    suspicious_words = [
        "login", "verify", "password", "account",
        "bank", "update", "secure", "confirm", "wallet"
    ]

    for word in suspicious_words:

        if word in url.lower():
            add_risk(10, "Suspicious keyword: " + word)

    if len(url) > 100:
        add_risk(10, "Unusually long URL")

    if port is not None and port not in (80, 443):
        add_risk(15, "Website uses an unusual port number")

    score = min(score, 100)

    if score >= 60:
        level = "High Risk"
        status = "Suspicious URL"

    elif score >= 30:
        level = "Medium Risk"
        status = "Warning"

    else:
        level = "Low Risk"
        status = "No obvious suspicious indicators"

    report = {
        "scan_type": "URL Threat Analysis",
        "input_text": url[:2000],
        "status": status,
        "risk_score": score,
        "risk_level": level,
        "indicators": found
    }

    session["latest_report"] = report
    save_scan(report)

    return render_template(
        "index.html",
        url_result="Advanced URL analysis completed.",
        url_status=status,
        url_score=score,
        url_level=level,
        url_found=found
    )


