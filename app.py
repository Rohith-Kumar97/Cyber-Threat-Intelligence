def get_db():
    conn = sqlite3.connect("users.db")
    conn.row_factory = sqlite3.Row
    return conn


def init_db():

    conn = get_db()

    conn.execute("""
        CREATE TABLE IF NOT EXISTS users (
            id INTEGER PRIMARY KEY AUTOINCREMENT,
            username TEXT NOT NULL,
            email TEXT UNIQUE NOT NULL,
            password TEXT NOT NULL
        )
    """)

    conn.execute("""
        CREATE TABLE IF NOT EXISTS scan_history (
            id INTEGER PRIMARY KEY AUTOINCREMENT,
            user_id INTEGER NOT NULL,
            scan_type TEXT NOT NULL,
            input_text TEXT,
            status TEXT,
            risk_score INTEGER,
            risk_level TEXT,
            indicators TEXT,
            created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
            FOREIGN KEY(user_id) REFERENCES users(id)
        )
    """)

    conn.commit()
    conn.close()


init_db()


# ==================================
# LOGIN PROTECTION
# ==================================

def login_required(func):

    @wraps(func)
    def wrapper(*args, **kwargs):

        if "user_id" not in session:
            return redirect(url_for("login"))

        return func(*args, **kwargs)

    return wrapper


# ==================================
# SAVE SCAN
# ==================================

def save_scan(report):

    conn = get_db()

    try:
        conn.execute("""
            INSERT INTO scan_history (
                user_id, scan_type, input_text,
                status, risk_score, risk_level, indicators
            )
            VALUES (?, ?, ?, ?, ?, ?, ?)
        """, (
            session["user_id"],
            report["scan_type"],
            report["input_text"],
            report["status"],
            report["risk_score"],
            report["risk_level"],
            json.dumps(report["indicators"])
        ))

        conn.commit()

    finally:
        conn.close()


# ==================================
# PDF GENERATOR
# ==================================

def create_pdf(report):

    buffer = BytesIO()

    pdf = SimpleDocTemplate(
        buffer,
        pagesize=A4,
        rightMargin=40,
        leftMargin=40,
        topMargin=40,
        bottomMargin=40
    )

    styles = getSampleStyleSheet()
    story = []

    story.append(Paragraph(
        "AI Cyber Threat Intelligence",
        styles["Title"]
    ))

    story.append(Spacer(1, 20))

    story.append(Paragraph(
        "Security Analysis Report",
        styles["Heading1"]
    ))

    story.append(Spacer(1, 15))

    fields = [
        ("Scan Type", report["scan_type"]),
        ("Scanned Content", report["input_text"]),
        ("Status", report["status"]),
        ("Risk Score", str(report["risk_score"]) + "/100"),
        ("Risk Level", report["risk_level"])
    ]

    for label, value in fields:

        story.append(Paragraph(
            "<b>" + escape(label) + ":</b> "
            + escape(str(value)),
            styles["Normal"]
        ))

        story.append(Spacer(1, 10))

    story.append(Paragraph(
        "Detected Indicators",
        styles["Heading2"]
    ))

    indicators = report.get("indicators", [])

    if indicators:

        for item in indicators:

            story.append(Paragraph(
                "- " + escape(str(item)),
                styles["Normal"]
            ))

            story.append(Spacer(1, 5))

    else:

        story.append(Paragraph(
            "No obvious suspicious indicators detected.",
            styles["Normal"]
        ))

    story.append(Spacer(1, 20))

    story.append(Paragraph(
        "Note: This report uses rule-based security checks. "
        "It cannot guarantee that scanned content is safe "
        "or malicious.",
        styles["Italic"]
    ))

    story.append(Spacer(1, 15))

    story.append(Paragraph(
        "Generated by AI Cyber Threat Intelligence Project - 2026",
        styles["Normal"]
    ))

    pdf.build(story)
    buffer.seek(0)

    return buffer


