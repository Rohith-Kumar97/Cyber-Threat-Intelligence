@app.route("/dashboard")
@login_required
def dashboard():

    conn = get_db()

    stats = conn.execute("""
        SELECT
            COUNT(*) AS total,
            SUM(CASE WHEN risk_level = 'Low Risk'
                THEN 1 ELSE 0 END) AS low,
            SUM(CASE WHEN risk_level = 'Medium Risk'
                THEN 1 ELSE 0 END) AS medium,
            SUM(CASE WHEN risk_level = 'High Risk'
                THEN 1 ELSE 0 END) AS high
        FROM scan_history
        WHERE user_id = ?
    """, (session["user_id"],)).fetchone()

    recent_scans = conn.execute("""
        SELECT *
        FROM scan_history
        WHERE user_id = ?
        ORDER BY id DESC
        LIMIT 5
    """, (session["user_id"],)).fetchall()

    conn.close()

    return render_template(
        "dashboard.html",
        stats=stats,
        recent_scans=recent_scans
    )


